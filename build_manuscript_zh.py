def equation(num, width_inch=5.4):
    """插入带编号的公式（居中，右端编号）。

    优先使用 **Word 原生公式 (OMML)** —— 公式在 Word 中可直接双击编辑、
    可随字号缩放不失真，符合期刊对"可编辑公式"的要求。
    若 equations_omml.py 缺失或该编号无对应 OMML，则回退到旧的 PNG 图片方式。

    版式：中部制表位放公式，右端制表位放编号 (n)。
    """
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.tab_stops.add_tab_stop(Inches(3.15), WD_TAB_ALIGNMENT.CENTER)
    p.paragraph_format.tab_stops.add_tab_stop(Inches(6.30), WD_TAB_ALIGNMENT.RIGHT)

    xml = EQ_OMML.get(num) if EQ_OMML else None
    if xml:
        p.add_run("\t")
        p._p.append(parse_xml(xml))
        p.add_run(f"\t({num})")
        return p

    # 回退：旧的 PNG 图片方式
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run()
    r.add_picture(os.path.join(EQDIR, f"eq{num}.png"), width=Inches(width_inch))
    return p


def add_table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        r = hdr[i].paragraphs[0].add_run(h)
        set_cjk(r, HT, 9.5, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, c in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(c))
            set_cjk(r, CN, 9.5)
    if widths:
        from docx.shared import Inches as _In
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = _In(w)
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(4)
    return t


