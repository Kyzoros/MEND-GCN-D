def para(t, size=11, italic=False, color=None, indent=True):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.line_spacing = 1.45
    if indent:
        p.paragraph_format.first_line_indent = Pt(22)
    if isinstance(t, list):
        for piece in t:
            r = p.add_run(piece)
            set_cjk(r, CN, size, italic=italic, color=color)
    else:
        r = p.add_run(t)
        set_cjk(r, CN, size, italic=italic, color=color)
    return p


