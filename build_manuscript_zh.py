h2("1.2 相关工作")
h3("1.2.1 基于靶点富集的经典方法")
para("最直接的一类方法是靶点集合富集分析：给定草药的成分靶点集合与疾病的差异表达基因（DEG）集合，"
     "以 Fisher 精确检验或超几何检验衡量二者重叠的显著性，将富集得分作为治疗可能性。这类方法（本文"
     "记为 D-TMS / HDmap-S）可解释性强、计算代价低，但存在两个固有缺陷：其一，它只利用单跳集合重叠，"
     "完全丢弃了靶点之间的通路拓扑关系；其二，富集统计量对“靶点数量”极度敏感——靶点多的草药天然"
     "更容易与任何疾病产生显著重叠，导致模型退化为一个“热度排序器”。更精细的方法会先对靶点在蛋白–"
     "蛋白互作（PPI）网络或 KEGG 通路网络上做随机游走扩散（RWR）再计算相似度，这引入了拓扑信息，"
     "但仍是无监督的，且扩散过程同样会放大高度节点的权重。")
h3("1.2.2 网络邻近度与基于扩散的方法")
para("网络邻近度（network proximity）方法直接计算草药靶点模块与疾病模块在网络上的平均最短路径或"
     "分离度，无需训练。RWR 扩散方法从种子节点出发做带重启的随机游走，用稳态分布衡量节点间的"
     "传播亲和度。这类方法的优势是不需要标注数据，在标注稀缺场景仍有可用性；但劣势同样明显——它们"
     "无法从数据中学习“什么样的拓扑模式对应真正的治疗”，只能依赖人工设计的先验相似度度量，且如上"
     "所述，扩散过程对节点度高度敏感，天然携带混杂。")
h3("1.2.3 图神经网络与链接预测")
para("图神经网络（GNN），特别是图卷积网络（GCN），通过多层消息传递聚合邻域信息，天然适合处理"
     "异质生物网络。在药物–疾病关联预测、药物重定位、药物–靶点互作预测等任务上，GCN 及其变体"
     "（GAT、GraphSAGE、异构图注意力网络等）已取得大量成功。知识图谱补全领域的解码器设计也提供了"
     "丰富工具：DistMult、ComplEx、TransR、ConvE 等打分函数各有适用场景。近年来已有若干工作尝试将"
     "图对比学习（graph contrastive learning）引入生物网络，通过对同一图施加不同的结构扰动（边删除、"
     "特征掩码、子图采样）构造对比视图，以 InfoNCE 损失最大化视图间一致性，从而在标注稀缺时学习到"
     "更鲁棒的表征。")
